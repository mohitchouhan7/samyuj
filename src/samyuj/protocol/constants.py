def derive_pc_sn(device_id_b64: str = "") -> str:
    raw = (device_id_b64 or "").strip().encode("utf-8")
    if not raw:
        return PC_SN_DEFAULT
    digest = hashlib.sha256(raw).hexdigest()[:8].upper()
    return f"SAM-PC-{digest}"
